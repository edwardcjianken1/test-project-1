function greetUser(name) {
  //Declares a function named greetUser that takes a parameter name.
  console.log("Hello,", name, "!"); //The function prints "Hello, [name]!" to console when the function is called.
}

greetUser("Edward"); //Calls greetUser function with "Edward" being passed as the parameter name
greetUser("Alice"); //Calls greetUser function with "Alice" being passed as the parameter name
greetUser("James"); //Calls greetUser function with "James" being passed as the parameter name

//Functions is very helpful to avoid repeating code. Instead of writing individual code to greet each user, a function can be created and called for each user. This saves effort of writing code and increases the efficiency of code execution.
